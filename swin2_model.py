def run_train(args: argparse.Namespace) -> int:
    os.makedirs(args.outdir, exist_ok=True)

    if args.resume_checkpoint:
        (
            resume_checkpoint,
            cfg,
            model,
            dist_head,
            loss_hm,
            loss_dist,
            opt,
        ) = load_checkpoint_training_runtime(
            args.resume_checkpoint,
            epochs=args.epochs,
            batch_size=args.batch_size,
            lr=args.lr,
            num_workers=args.num_workers,
            scheduler=args.scheduler,
            warmup_epochs=args.warmup_epochs,
            warmup_start_factor=args.warmup_start_factor,
            min_lr_ratio=args.min_lr_ratio,
            early_stop_patience=args.early_stop_patience,
            backbone=args.backbone,
            backbone_preset=args.backbone_preset,
            pretrained=args.pretrained,
            backbone_feature_index=args.backbone_feature_index,
            decoder_channels=args.decoder_channels,
        )
        subset_mask = resume_checkpoint["subset_mask"].bool()
        kp_weight = resume_checkpoint["kp_weight"].float()
        template_Tn = resume_checkpoint["template_Tn"].float()
        start_epoch = int(resume_checkpoint.get("epoch", 0)) + 1
        best = float(
            resume_checkpoint.get(
                "best_val_loss", resume_checkpoint.get("val_loss", float("inf"))
            )
        )
        best_kp_error = float(
            resume_checkpoint.get(
                "best_val_kp_error",
                resume_checkpoint.get("val_kp_error", float("inf")),
            )
        )
        previous_eval_kp_error = resume_checkpoint.get("val_kp_error")
        if not isinstance(previous_eval_kp_error, (int, float)):
            previous_eval_kp_error = None
        raw_epochs_without_improvement = resume_checkpoint.get(
            "epochs_without_improvement", 0
        )
        if isinstance(raw_epochs_without_improvement, (int, float)):
            epochs_without_improvement = max(int(raw_epochs_without_improvement), 0)
        else:
            epochs_without_improvement = 0
    else:
        resume_checkpoint = None
        cfg = config_from_args(
            epochs=args.epochs,
            batch_size=args.batch_size,
            lr=args.lr,
            num_workers=args.num_workers,
            scheduler=args.scheduler,
            warmup_epochs=args.warmup_epochs,
            warmup_start_factor=args.warmup_start_factor,
            min_lr_ratio=args.min_lr_ratio,
            early_stop_patience=args.early_stop_patience,
            backbone=args.backbone,
            backbone_preset=args.backbone_preset,
            pretrained=args.pretrained,
            backbone_feature_index=args.backbone_feature_index,
            decoder_channels=args.decoder_channels,
        )
        subset_mask, kp_weight = build_subset_and_weights(cfg)
        template_Tn = load_template_Tn(args.template_data, cfg)
        model, dist_head, loss_hm, loss_dist = build_runtime_components(
            cfg,
            template_Tn.to(cfg.device),
            subset_mask.to(cfg.device),
            kp_weight.to(cfg.device),
        )
        opt = torch.optim.AdamW(
            list(model.parameters()) + list(dist_head.parameters()),
            lr=cfg.lr,
            weight_decay=cfg.weight_decay,
        )
        start_epoch = 1
        best = float("inf")
        best_kp_error = float("inf")
        previous_eval_kp_error = None
        epochs_without_improvement = 0

    if cfg.early_stop_patience is not None and not args.val_data:
        raise ValueError("--val-data is required when early stopping is enabled")

    # Load items
    train_items, train_summary = load_frame_items_with_summary(args.train_data)
    print_frame_summary("train", train_summary)
    if not train_items:
        raise ValueError("No usable training rows were found in the training data")

    val_summary = None
    if args.val_data:
        val_items, val_summary = load_frame_items_with_summary(args.val_data)
        print_frame_summary("val", val_summary)
        if not val_items:
            raise ValueError(
                "No usable validation rows were found in the validation data"
            )
    else:
        val_items = None

    # Datasets / loaders
    train_loader = build_loader(
        train_items,
        template_Tn,
        subset_mask,
        kp_weight,
        cfg,
        shuffle=True,
        drop_last=True,
    )

    if val_items:
        val_loader = build_loader(
            val_items,
            template_Tn,
            subset_mask,
            kp_weight,
            cfg,
            shuffle=False,
            drop_last=False,
        )
    else:
        val_loader = None

    resolved_tensorboard_dir = resolve_resume_tensorboard_dir(
        args.tensorboard_dir,
        args.outdir,
        resume_checkpoint,
    )
    writer, tensorboard_dir = build_tensorboard_writer(
        args.outdir, resolved_tensorboard_dir
    )
    writer.add_text(
        "config/json", json.dumps(cfg.__dict__, sort_keys=True, indent=2), 0
    )
    if train_summary is not None:
        writer.add_text("data/train_summary", str(train_summary), 0)
    if val_summary is not None:
        writer.add_text("data/val_summary", str(val_summary), 0)
    if resume_checkpoint is not None:
        writer.add_text(
            "resume/checkpoint", str(args.resume_checkpoint), start_epoch - 1
        )
        writer.add_text(
            "resume/metadata",
            json.dumps(
                {
                    "start_epoch": start_epoch,
                    "best_val_loss": best,
                    "previous_logdir": resume_checkpoint.get("tensorboard", {}).get(
                        "logdir"
                    ),
                },
                sort_keys=True,
                indent=2,
            ),
            start_epoch - 1,
        )
    print(f"tensorboard logs: {tensorboard_dir}")
    print(
        f"optimizer: base_lr={cfg.lr:.2e} scheduler={cfg.scheduler or 'none'} "
        f"warmup_epochs={cfg.warmup_epochs} min_lr_ratio={cfg.min_lr_ratio:.3f}"
    )
    try:
        for epoch in range(start_epoch, cfg.epochs + 1):
            epoch_lr = learning_rate_for_epoch(cfg, epoch)
            set_optimizer_lr(opt, epoch_lr)
            tr = train_one_epoch(
                model, dist_head, train_loader, opt, loss_hm, loss_dist, cfg
            )

            if val_loader is not None:
                va = eval_one_epoch(
                    model, dist_head, val_loader, loss_hm, loss_dist, cfg
                )
            else:
                va = {
                    "loss": tr["loss"],
                    "loss_hm": tr["loss_hm"],
                    "loss_dist": tr["loss_dist"],
                    "kp_error": tr["kp_error"],
                }

            write_metrics_to_tensorboard(
                writer,
                epoch,
                train_metrics=tr,
                val_metrics=va,
                lr=epoch_lr,
            )
            write_example_artifacts_to_tensorboard(
                writer, epoch, "train", tr.get("example")
            )
            write_example_artifacts_to_tensorboard(
                writer, epoch, "val", va.get("example")
            )

            print(
                f"epoch {epoch:03d} | "
                f"train loss={tr['loss']:.4f} (hm={tr['loss_hm']:.4f}, dist={tr['loss_dist']:.4f}, kp={tr['kp_error']:.4f}) | "
                f"val loss={va['loss']:.4f} (hm={va['loss_hm']:.4f}, dist={va['loss_dist']:.4f}, kp={va['kp_error']:.4f})"
            )

            current_eval_kp_error = float(va["kp_error"])
            alert = format_kp_error_regression_alert(
                epoch=epoch,
                current_kp_error=current_eval_kp_error,
                previous_kp_error=previous_eval_kp_error,
                best_kp_error=(
                    None if not math.isfinite(best_kp_error) else best_kp_error
                ),
                split_name=("val" if val_loader is not None else "train"),
            )
            if alert is not None:
                print(alert)

            current_val_loss = float(va["loss"])
            improved = current_val_loss < best
            if improved:
                best = current_val_loss
                epochs_without_improvement = 0
            else:
                epochs_without_improvement += 1

            best_after_epoch = float(best)
            best_kp_error_after_epoch = min(best_kp_error, current_eval_kp_error)

            ckpt = {
                "epoch": epoch,
                "cfg": cfg.__dict__,
                "kp_order": BP,
                "subset_mask": subset_mask.cpu(),
                "kp_weight": kp_weight.cpu(),
                "template_Tn": template_Tn.cpu(),
                "model": model.state_dict(),
                "dist_head": dist_head.state_dict(),
                "opt": opt.state_dict(),
                "scheduler": scheduler_state_for_checkpoint(cfg, epoch, epoch_lr),
                "val_loss": current_val_loss,
                "val_kp_error": current_eval_kp_error,
                "best_val_loss": best_after_epoch,
                "best_val_kp_error": float(best_kp_error_after_epoch),
                "epochs_without_improvement": epochs_without_improvement,
                "tensorboard": {
                    "logdir": tensorboard_dir,
                    "last_epoch": epoch,
                },
                "train_run": {
                    "outdir": args.outdir,
                    "train_data": args.train_data,
                    "val_data": args.val_data,
                    "template_data": args.template_data,
                    "resume_checkpoint": args.resume_checkpoint,
                },
            }

            torch.save(ckpt, os.path.join(args.outdir, f"ckpt_epoch_{epoch:03d}.pt"))
            if improved:
                writer.add_scalar("best/val_loss", best, epoch)
                torch.save(ckpt, os.path.join(args.outdir, "best.pt"))
            if (
                cfg.early_stop_patience is not None
                and epochs_without_improvement >= cfg.early_stop_patience
            ):
                print(
                    f"early stopping at epoch {epoch:03d}: "
                    f"val_loss={current_val_loss:.4f} best_val_loss={best:.4f} "
                    f"patience={cfg.early_stop_patience}"
                )
                best_kp_error = best_kp_error_after_epoch
                previous_eval_kp_error = current_eval_kp_error
                break
            best_kp_error = best_kp_error_after_epoch
            previous_eval_kp_error = current_eval_kp_error
        writer.flush()
    finally:
        writer.close()

    print(f"done. best val loss = {best:.4f}")
    return 0


def run_test(args: argparse.Namespace) -> int:
    (
        checkpoint,
        cfg,
        model,
        dist_head,
        loss_hm,
        loss_dist,
    ) = load_checkpoint_runtime(
        args.checkpoint,
        batch_size=args.batch_size,
        num_workers=args.num_workers,
    )
    provenance = format_checkpoint_provenance(checkpoint, args.checkpoint)
    if provenance is not None:
        print(provenance)
    eval_metadata = format_eval_metadata(
        checkpoint,
        checkpoint_path=args.checkpoint,
        test_data=args.test_data,
        cfg=cfg,
    )
    if eval_metadata is not None:
        print(eval_metadata)

    template_Tn = checkpoint["template_Tn"].float()
    subset_mask = checkpoint["subset_mask"].bool()
    kp_weight = checkpoint["kp_weight"].float()

    test_items, test_summary = load_frame_items_with_summary(args.test_data)
    print_frame_summary("test", test_summary)
    if not test_items:
        raise ValueError("No usable test rows were found in the test data")

    test_loader = build_loader(
        test_items,
        template_Tn,
        subset_mask,
        kp_weight,
        cfg,
        shuffle=False,
        drop_last=False,
    )
    metrics = eval_one_epoch(model, dist_head, test_loader, loss_hm, loss_dist, cfg)
    print(
        f"test loss={metrics['loss']:.4f} "
        f"(hm={metrics['loss_hm']:.4f}, dist={metrics['loss_dist']:.4f}, kp={metrics['kp_error']:.4f})"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = build_argument_parser()
    args = ap.parse_args(argv)

    if args.mode == "train":
        if not args.train_data:
            ap.error("--train-data is required in train mode")
        if not args.template_data and not args.resume_checkpoint:
            ap.error("--template-data is required in train mode")
        if not args.outdir:
            ap.error("--outdir is required in train mode")
        if args.early_stop_patience is not None and args.early_stop_patience < 1:
            ap.error("--early-stop-patience must be at least 1")
        if args.early_stop_patience is not None and not args.val_data:
            ap.error("--val-data is required when --early-stop-patience is set")
        if args.resume_checkpoint and not os.path.exists(args.resume_checkpoint):
            ap.error("--resume-checkpoint must point to an existing checkpoint")
        return run_train(args)

    if not args.test_data:
        ap.error("--test-data is required in test mode")
    if not args.checkpoint:
        ap.error("--checkpoint is required in test mode")
    return run_test(args)


if __name__ == "__main__":
    raise SystemExit(main())
