# ----------------------------
# Parse your frame-level DLC record
# ----------------------------
def extract_xy_conf_from_record(
    record: Dict[str, Any],
) -> tuple[np.ndarray, np.ndarray]:
    """
    record["bodyparts"][0] is a list of length K of [x,y,conf].
    Returns:
      xy: (K,2) float32
      cf: (K,) float32
    """
    pts = record["bodyparts"][0]
    arr = np.asarray(pts, dtype=np.float32)  # (K,3)
    if arr.shape[0] != K:
        raise ValueError(f"Expected K={K} keypoints, got {arr.shape[0]}")
    xy = arr[:, :2].copy()
    cf = arr[:, 2].copy()
    return xy, cf


# ----------------------------
# Heatmap utils
# ----------------------------
def gaussian_2d(
    height: int, width: int, cx: float, cy: float, sigma: float, device
) -> torch.Tensor:
    yy = torch.arange(height, device=device).float().view(-1, 1)
    xx = torch.arange(width, device=device).float().view(1, -1)
    return torch.exp(-((xx - cx) ** 2 + (yy - cy) ** 2) / (2.0 * sigma * sigma))


def make_heatmaps(
    keypoints_xy: torch.Tensor,  # (K,2) in resized image coords
    valid: torch.Tensor,  # (K,) bool
    out_h: int,
    out_w: int,
    in_h: int,
    in_w: int,
    sigma_px_out: float,
) -> torch.Tensor:
    device = keypoints_xy.device
    heatmaps = torch.zeros((keypoints_xy.shape[0], out_h, out_w), device=device)

    sx = out_w / float(in_w)
    sy = out_h / float(in_h)

    for k in range(keypoints_xy.shape[0]):
        if not bool(valid[k]):
            continue
        x, y = keypoints_xy[k]
        cx = (x * sx).float()
        cy = (y * sy).float()
        if cx < 0 or cy < 0 or cx >= out_w or cy >= out_h:
            continue
        heatmaps[k] = gaussian_2d(
            out_h, out_w, float(cx), float(cy), sigma_px_out, device
        )

    return heatmaps


# ----------------------------
# Soft-argmax (differentiable keypoint decoding)
# ----------------------------
def soft_argmax_2d(heatmaps: torch.Tensor, beta: float = 50.0) -> torch.Tensor:
    """
    heatmaps: (B,K,H,W) logits
    returns:  (B,K,2) in heatmap pixel coords (x,y)
    """
    B, K_, H, W = heatmaps.shape
    h = heatmaps.reshape(B, K_, H * W)
    p = F.softmax(h * beta, dim=-1)

    xs = torch.linspace(0, W - 1, W, device=heatmaps.device)
    ys = torch.linspace(0, H - 1, H, device=heatmaps.device)
    yy, xx = torch.meshgrid(ys, xs, indexing="ij")
    grid = torch.stack([xx.reshape(-1), yy.reshape(-1)], dim=-1)  # (HW,2)

    coords = torch.einsum("bkh,hd->bkd", p, grid)
    return coords


# ----------------------------
# Template normalization
# ----------------------------
def normalize_template_neck_backmid(
    T_xy_resized: torch.Tensor, eps: float = 1e-6
) -> torch.Tensor:
    """
    T_xy_resized: (K,2) in resized (384-space) coords
    returns Tn: (K,2) centered at neck_base, scaled by ||back_mid - neck_base||
    """
    sh = T_xy_resized[IDX_NECK_BASE]
    scale = torch.norm(T_xy_resized[IDX_BACK_MID] - sh) + eps
    return (T_xy_resized - sh[None, :]) / scale


# ----------------------------
# Pattern-3 target metric (orientation-aware, smooth L2, NOT rotation-invariant)
# ----------------------------
def grab_distance_target(
    X_xy_resized: torch.Tensor,  # (K,2) in resized coords (384-space)
    conf: torch.Tensor,  # (K,)
    Tn: torch.Tensor,  # (K,2) normalized template
    subset_mask: torch.Tensor,  # (K,) bool
    kp_weight: torch.Tensor,  # (K,)
    cfg: Config,
) -> torch.Tensor:
    valid = subset_mask & (conf >= cfg.conf_min)
    w = kp_weight * conf * valid.float()

    sh = X_xy_resized[IDX_NECK_BASE]
    back_mid = X_xy_resized[IDX_BACK_MID]
    nose = X_xy_resized[IDX_NOSE]

    Xc = X_xy_resized - sh[None, :]
    scale = torch.norm(back_mid - sh) + cfg.eps
    Xn = Xc / scale

    diff = Xn - Tn
    per_k = (diff**2).sum(dim=1)
    d_shape = torch.sqrt((w * per_k).sum() / (w.sum() + cfg.eps))

    # Smooth L2 horizontal penalty from torso axis back_mid - neck_base
    v_orient = (back_mid - sh) / (scale + cfg.eps)
    d_horiz = torch.sqrt((v_orient[1] ** 2) / (v_orient[0] ** 2 + cfg.eps))

    # Direction: require nose left of body => (back_mid - nose).x > 0
    v_dir = (back_mid - nose) / (scale + cfg.eps)
    d_dir = F.relu(-v_dir[0])

    # Rearing proxy: nose->neck_base verticality
    v2 = (sh - nose) / (scale + cfg.eps)
    rear_proxy = torch.sqrt((v2[1] ** 2) / (v2[0] ** 2 + cfg.eps))
    d_rear = F.relu(rear_proxy - cfg.rear_thresh)

    return (
        d_shape
        + cfg.gamma_orient * d_horiz
        + cfg.gamma_dir * d_dir
        + cfg.gamma_rear * d_rear
    )


# ----------------------------
# Losses
# ----------------------------
class WeightedHeatmapMSE(nn.Module):
    kp_w: torch.Tensor

    def __init__(self, kp_weight: torch.Tensor, eps: float = 1e-8):
        super().__init__()
        self.register_buffer("kp_w", kp_weight.float())
        self.eps = eps

    def forward(
        self,
        pred: torch.Tensor,
        target: torch.Tensor,
        conf: torch.Tensor,
        valid: torch.Tensor,
    ) -> torch.Tensor:
        """
        pred/target: (B,K,H,W)
        conf: (B,K)
        valid: (B,K) float {0,1}
        """
        w = self.kp_w[None, :] * conf * valid
        mse = (pred - target) ** 2
        mse = mse.mean(dim=(2, 3))
        return (w * mse).sum() / (w.sum() + self.eps)


# ----------------------------
# Pose model (heatmaps)
# ----------------------------
class SimpleUpsampleHead(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_keypoints: int,
        out_size: int,
        out_channels: int = 256,
    ):
        super().__init__()
        self.out_size = out_size
        self.block = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, 3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, 3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, 3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, num_keypoints, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        heatmaps = self.block(x)
        if heatmaps.shape[-2:] != (self.out_size, self.out_size):
            heatmaps = F.interpolate(
                heatmaps,
                size=(self.out_size, self.out_size),
                mode="bilinear",
                align_corners=False,
            )
        return heatmaps


class ImageNetInputNormalizer(nn.Module):
    mean: torch.Tensor
    std: torch.Tensor

    def __init__(self):
        super().__init__()
        self.register_buffer(
            "mean", torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1)
        )
        self.register_buffer(
            "std", torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1)
        )

    def forward(self, images: torch.Tensor) -> torch.Tensor:
        return (images - self.mean) / self.std


class PoseNetResNet(nn.Module):
    """
    Input: (B,3,384,384) -> heatmaps: (B,K,96,96)
    """

    def __init__(
        self,
        num_keypoints: int,
        heatmap_size: int,
        decoder_channels: int,
        pretrained: bool,
    ):
        super().__init__()
        weights = (
            torchvision.models.ResNet18_Weights.IMAGENET1K_V1 if pretrained else None
        )
        backbone = torchvision.models.resnet18(weights=weights)
        self.normalizer = ImageNetInputNormalizer()
        self.stem = nn.Sequential(
            backbone.conv1,
            backbone.bn1,
            backbone.relu,
            backbone.maxpool,
            backbone.layer1,
            backbone.layer2,
            backbone.layer3,
        )
        self.head = SimpleUpsampleHead(
            in_channels=256,
            num_keypoints=num_keypoints,
            out_size=heatmap_size,
            out_channels=decoder_channels,
        )

    def forward(self, images: torch.Tensor) -> torch.Tensor:
        feat = self.stem(self.normalizer(images))
        return self.head(feat)


class PoseNetTimm(nn.Module):
    def __init__(
        self,
        backbone_name: str,
        num_keypoints: int,
        heatmap_size: int,
        decoder_channels: int,
        pretrained: bool,
        feature_index: int,
    ):
        super().__init__()
        self.normalizer = ImageNetInputNormalizer()
        self.backbone = timm.create_model(
            backbone_name,
            pretrained=pretrained,
            features_only=True,
            out_indices=(feature_index,),
        )
        self.backbone_out_channels = int(self.backbone.feature_info.channels()[0])  # type: ignore
        self.head = SimpleUpsampleHead(
            in_channels=self.backbone_out_channels,
            num_keypoints=num_keypoints,
            out_size=heatmap_size,
            out_channels=decoder_channels,
        )

    def forward(self, images: torch.Tensor) -> torch.Tensor:
        feat = self.backbone(self.normalizer(images))[0]
        if feat.ndim != 4:
            raise ValueError(
                f"Expected a 4D feature map from timm backbone, got {feat.shape}"
            )
        if (
            feat.shape[1] != self.backbone_out_channels
            and feat.shape[-1] == self.backbone_out_channels
        ):
            feat = feat.permute(0, 3, 1, 2).contiguous()
        return self.head(feat)


def build_pose_model(cfg: Config, num_keypoints: int) -> nn.Module:
    if cfg.backbone == "resnet18":
        return PoseNetResNet(
            num_keypoints=num_keypoints,
            heatmap_size=cfg.heatmap_size,
            decoder_channels=cfg.decoder_channels,
            pretrained=cfg.pretrained,
        )

    return PoseNetTimm(
        backbone_name=cfg.backbone,
        num_keypoints=num_keypoints,
        heatmap_size=cfg.heatmap_size,
        decoder_channels=cfg.decoder_channels,
        pretrained=cfg.pretrained,
        feature_index=cfg.backbone_feature_index,
    )


# ----------------------------
# Exact-metric Pattern-3 head (from predicted heatmaps)
# ----------------------------
class ExactMetricDistanceHead(nn.Module):
    """
    Decodes keypoints via soft-argmax and computes:
      d_hat = shape_to_template(Xn,Tn) + penalties

    IMPORTANT:
    - This head uses fixed weights (subset + kp_weight) and does not use DLC conf at inference.
    """

    subset_mask: torch.Tensor
    kp_weight: torch.Tensor
    Tn: torch.Tensor

    def __init__(
        self,
        template_Tn: torch.Tensor,
        subset_mask: torch.Tensor,
        kp_weight: torch.Tensor,
        cfg: Config,
    ):
        super().__init__()
        self.cfg = cfg
        self.register_buffer("Tn", template_Tn.float())
        self.register_buffer("subset_mask", subset_mask.bool())
        self.register_buffer("kp_weight", kp_weight.float())

    def forward(self, heatmaps: torch.Tensor) -> tuple[torch.Tensor, dict]:
        cfg = self.cfg
        B, K_, H, W = heatmaps.shape
        assert K_ == K and H == cfg.heatmap_size and W == cfg.heatmap_size

        # Decode in heatmap coords, then scale to resized-image coords (384-space)
        coords_hm = soft_argmax_2d(heatmaps, beta=cfg.softargmax_beta)  # (B,K,2)
        coords = coords_hm * float(cfg.stride)  # (B,K,2)

        sh = coords[:, IDX_NECK_BASE, :]
        back_mid = coords[:, IDX_BACK_MID, :]
        nose = coords[:, IDX_NOSE, :]

        Xc = coords - sh[:, None, :]
        scale = torch.norm(back_mid - sh, dim=-1) + cfg.eps
        Xn = Xc / scale[:, None, None]

        # shape distance on subset
        mask = self.subset_mask[None, :].float()
        w = self.kp_weight[None, :] * mask

        diff = Xn - self.Tn[None, :, :]
        per_k = (diff**2).sum(dim=-1)
        d_shape = torch.sqrt((w * per_k).sum(dim=1) / (w.sum(dim=1) + cfg.eps))

        # smooth L2 horiz penalty on torso axis
        v_orient = (back_mid - sh) / (scale[:, None] + cfg.eps)
        d_horiz = torch.sqrt((v_orient[:, 1] ** 2) / (v_orient[:, 0] ** 2 + cfg.eps))

        # direction
        v_dir = (back_mid - nose) / (scale[:, None] + cfg.eps)
        d_dir = F.relu(-v_dir[:, 0])

        # rearing proxy
        v2 = (sh - nose) / (scale[:, None] + cfg.eps)
        rear_proxy = torch.sqrt((v2[:, 1] ** 2) / (v2[:, 0] ** 2 + cfg.eps))
        d_rear = F.relu(rear_proxy - cfg.rear_thresh)

        d_hat = (
            d_shape
            + cfg.gamma_orient * d_horiz
            + cfg.gamma_dir * d_dir
            + cfg.gamma_rear * d_rear
        )

        dbg = {
            "d_shape": d_shape.detach(),
            "d_horiz": d_horiz.detach(),
            "d_dir": d_dir.detach(),
            "rear_proxy": rear_proxy.detach(),
            "d_rear": d_rear.detach(),
        }
        return d_hat, dbg


