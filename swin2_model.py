def load_template_Tn(template_json: str, cfg: Config) -> torch.Tensor:
    """
    Loads template record, scales template keypoints (original pixels -> resized 384-space),
    then normalizes to Tn (center neck_base, scale by neck_base->back_middle).
    """
    if Path(template_json).suffix.lower() == ".csv":
        template = _load_template_from_annotation_csv(template_json)
        img_path = template.image_path
        xy = template.xy
    else:
        rec = json.loads(Path(template_json).read_text())
        if isinstance(rec, list):
            if len(rec) != 1:
                raise ValueError("template_json as list must contain exactly 1 record")
            rec = rec[0]

        img_path = rec["image_path"]
        xy, _cf = extract_xy_conf_from_record(rec)  # xy is original pixels

    img = Image.open(img_path).convert("RGB")
    ow, oh = img.size

    sx = cfg.image_size / float(ow)
    sy = cfg.image_size / float(oh)
    xy_rs = torch.tensor(xy, dtype=torch.float32)
    xy_rs[:, 0] *= sx
    xy_rs[:, 1] *= sy

    Tn = normalize_template_neck_backmid(xy_rs, eps=cfg.eps)
    return Tn


def build_loader(
    items: List[FrameItem],
    template_Tn: torch.Tensor,
    subset_mask: torch.Tensor,
    kp_weight: torch.Tensor,
    cfg: Config,
    *,
    shuffle: bool,
    drop_last: bool,
) -> DataLoader:
    dataset = RodentPoseDataset(items, template_Tn, subset_mask, kp_weight, cfg)
    return DataLoader(
        dataset,
        batch_size=cfg.batch_size,
        shuffle=shuffle,
        num_workers=cfg.num_workers,
        pin_memory=(cfg.device == "cuda"),
        drop_last=drop_last,
    )


def build_runtime_components(
    cfg: Config,
    template_Tn: torch.Tensor,
    subset_mask: torch.Tensor,
    kp_weight: torch.Tensor,
) -> tuple[nn.Module, nn.Module, nn.Module, nn.Module]:
    model = build_pose_model(cfg, num_keypoints=K).to(cfg.device)
    dist_head = ExactMetricDistanceHead(template_Tn, subset_mask, kp_weight, cfg).to(
        cfg.device
    )
    loss_hm = WeightedHeatmapMSE(kp_weight).to(cfg.device)
    loss_dist = nn.SmoothL1Loss(beta=0.5)
    return model, dist_head, loss_hm, loss_dist


def config_from_args(
    *,
    base_cfg: Config | None = None,
    epochs: int | None = None,
    batch_size: int | None = None,
    lr: float | None = None,
    num_workers: int | None = None,
    scheduler: str | None = None,
    warmup_epochs: int | None = None,
    warmup_start_factor: float | None = None,
    min_lr_ratio: float | None = None,
    early_stop_patience: int | None = None,
    backbone: str | None = None,
    backbone_preset: str | None = None,
    pretrained: bool | None = None,
    backbone_feature_index: int | None = None,
    decoder_channels: int | None = None,
) -> Config:
    scheduler_was_explicitly_set = scheduler is not None
    scheduler_was_explicitly_disabled = scheduler == "none"
    if scheduler == "none":
        scheduler = None
    cfg = Config(**(base_cfg.__dict__ if base_cfg is not None else Config().__dict__))
    has_base_cfg = base_cfg is not None
    if epochs is not None:
        cfg.epochs = epochs
    if batch_size is not None:
        cfg.batch_size = batch_size
    if num_workers is not None:
        cfg.num_workers = num_workers
    if scheduler_was_explicitly_disabled:
        cfg.scheduler = None
    elif scheduler is not None:
        cfg.scheduler = scheduler
    if warmup_epochs is not None:
        cfg.warmup_epochs = warmup_epochs
    if warmup_start_factor is not None:
        cfg.warmup_start_factor = warmup_start_factor
    if min_lr_ratio is not None:
        cfg.min_lr_ratio = min_lr_ratio
    if early_stop_patience is not None:
        cfg.early_stop_patience = early_stop_patience
    if backbone is not None:
        cfg.backbone = backbone
    if backbone_preset is not None:
        cfg.backbone_preset = backbone_preset
    apply_backbone_preset(cfg, cfg.backbone_preset)
    if pretrained is not None:
        cfg.pretrained = pretrained
    if backbone_feature_index is not None:
        cfg.backbone_feature_index = backbone_feature_index
    if decoder_channels is not None:
        cfg.decoder_channels = decoder_channels
    user_provided_lr = lr is not None
    if lr is not None:
        cfg.lr = lr
    elif not has_base_cfg:
        cfg.lr = default_lr_for_backbone(cfg.backbone)
        apply_large_batch_training_defaults(
            cfg,
            user_provided_lr=user_provided_lr,
            user_provided_scheduler=scheduler_was_explicitly_set,
            user_provided_warmup_epochs=warmup_epochs is not None,
            user_provided_warmup_start_factor=warmup_start_factor is not None,
            user_provided_min_lr_ratio=min_lr_ratio is not None,
        )
    cfg.device = "cuda" if torch.cuda.is_available() else "cpu"
    return cfg


def config_from_checkpoint_dict(cfg_dict: dict[str, Any]) -> Config:
    defaults = Config()
    values = defaults.__dict__.copy()
    for key, value in cfg_dict.items():
        if key in values:
            values[key] = value
    return Config(**values)


def load_checkpoint_runtime(
    checkpoint_path: str,
    *,
    batch_size: int | None = None,
    num_workers: int | None = None,
) -> tuple[dict[str, Any], Config, nn.Module, nn.Module, nn.Module, nn.Module]:
    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    cfg = config_from_args(
        base_cfg=config_from_checkpoint_dict(checkpoint["cfg"]),
        batch_size=batch_size,
        num_workers=num_workers,
        pretrained=False,
    )

    template_Tn = checkpoint["template_Tn"].float().to(cfg.device)
    subset_mask = checkpoint["subset_mask"].bool().to(cfg.device)
    kp_weight = checkpoint["kp_weight"].float().to(cfg.device)
    model, dist_head, loss_hm, loss_dist = build_runtime_components(
        cfg, template_Tn, subset_mask, kp_weight
    )
    model.load_state_dict(checkpoint["model"])
    dist_head.load_state_dict(checkpoint["dist_head"])
    return checkpoint, cfg, model, dist_head, loss_hm, loss_dist


def load_checkpoint_training_runtime(
    checkpoint_path: str,
    *,
    epochs: int | None = None,
    batch_size: int | None = None,
    lr: float | None = None,
    num_workers: int | None = None,
    scheduler: str | None = None,
    warmup_epochs: int | None = None,
    warmup_start_factor: float | None = None,
    min_lr_ratio: float | None = None,
    early_stop_patience: int | None = None,
    backbone: str | None = None,
    backbone_preset: str | None = None,
    pretrained: bool | None = None,
    backbone_feature_index: int | None = None,
    decoder_channels: int | None = None,
) -> tuple[
    dict[str, Any],
    Config,
    nn.Module,
    nn.Module,
    nn.Module,
    nn.Module,
    torch.optim.Optimizer,
]:
    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    cfg = config_from_args(
        base_cfg=config_from_checkpoint_dict(checkpoint["cfg"]),
        epochs=epochs,
        batch_size=batch_size,
        lr=lr,
        num_workers=num_workers,
        scheduler=scheduler,
        warmup_epochs=warmup_epochs,
        warmup_start_factor=warmup_start_factor,
        min_lr_ratio=min_lr_ratio,
        early_stop_patience=early_stop_patience,
        backbone=backbone,
        backbone_preset=backbone_preset,
        pretrained=pretrained,
        backbone_feature_index=backbone_feature_index,
        decoder_channels=decoder_channels,
    )

    template_Tn = checkpoint["template_Tn"].float().to(cfg.device)
    subset_mask = checkpoint["subset_mask"].bool().to(cfg.device)
    kp_weight = checkpoint["kp_weight"].float().to(cfg.device)
    model, dist_head, loss_hm, loss_dist = build_runtime_components(
        cfg, template_Tn, subset_mask, kp_weight
    )
    model.load_state_dict(checkpoint["model"])
    dist_head.load_state_dict(checkpoint["dist_head"])

    opt = torch.optim.AdamW(
        list(model.parameters()) + list(dist_head.parameters()),
        lr=cfg.lr,
        weight_decay=cfg.weight_decay,
    )
    if "opt" in checkpoint:
        opt.load_state_dict(checkpoint["opt"])
        if lr is not None:
            set_optimizer_lr(opt, cfg.lr)
        else:
            scheduler_state = checkpoint.get("scheduler")
            if isinstance(scheduler_state, dict):
                last_lr = scheduler_state.get("last_lr")
                if isinstance(last_lr, (int, float)):
                    set_optimizer_lr(opt, float(last_lr))

    return checkpoint, cfg, model, dist_head, loss_hm, loss_dist, opt


