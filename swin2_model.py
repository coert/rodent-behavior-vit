def train_one_epoch(
    model, dist_head, loader, opt, loss_hm, loss_dist, cfg: Config
) -> dict[str, Any]:
    model.train()
    dist_head.train()
    amp_device = "cuda" if cfg.device == "cuda" else "cpu"
    scaler = torch.GradScaler(amp_device, enabled=(cfg.device == "cuda"))

    tot = tot_hm = tot_d = tot_kp = 0.0
    n = 0
    example = None

    for batch in tqdm(loader, desc="train", leave=False):
        images = batch["image"].to(cfg.device)
        hm_tgt = batch["heatmaps"].to(cfg.device)
        conf = batch["conf"].to(cfg.device)
        valid = batch["valid"].to(cfg.device)
        y = batch["y"].to(cfg.device)

        opt.zero_grad(set_to_none=True)

        with torch.autocast(amp_device, enabled=(cfg.device == "cuda")):
            hm_pred = model(images)
            d_hat, _dbg = dist_head(hm_pred)

            L_hm = loss_hm(hm_pred, hm_tgt, conf, valid)
            L_d = loss_dist(d_hat, y)
            L = L_hm + cfg.lambda_dist * L_d

        kp_err = decoded_keypoint_error(hm_pred, hm_tgt, conf, valid, cfg)

        scaler.scale(L).backward()
        scaler.step(opt)
        scaler.update()

        if example is None:
            example = capture_tensorboard_example(
                images,
                hm_tgt,
                hm_pred,
                image_size=cfg.image_size,
                softargmax_beta=cfg.softargmax_beta,
            )

        tot += float(L.item())
        tot_hm += float(L_hm.item())
        tot_d += float(L_d.item())
        tot_kp += float(kp_err.item())
        n += 1

    return {
        "loss": tot / max(n, 1),
        "loss_hm": tot_hm / max(n, 1),
        "loss_dist": tot_d / max(n, 1),
        "kp_error": tot_kp / max(n, 1),
        "example": example,
    }


@torch.no_grad()
def eval_one_epoch(model, dist_head, loader, loss_hm, loss_dist, cfg: Config) -> dict:
    model.eval()
    dist_head.eval()
    tot = tot_hm = tot_d = tot_kp = 0.0
    n = 0
    example = None

    for batch in tqdm(loader, desc="eval", leave=False):
        images = batch["image"].to(cfg.device)
        hm_tgt = batch["heatmaps"].to(cfg.device)
        conf = batch["conf"].to(cfg.device)
        valid = batch["valid"].to(cfg.device)
        y = batch["y"].to(cfg.device)

        hm_pred = model(images)
        d_hat, _dbg = dist_head(hm_pred)

        if example is None:
            example = capture_tensorboard_example(
                images,
                hm_tgt,
                hm_pred,
                image_size=cfg.image_size,
                softargmax_beta=cfg.softargmax_beta,
            )

        L_hm = loss_hm(hm_pred, hm_tgt, conf, valid)
        L_d = loss_dist(d_hat, y)
        L = L_hm + cfg.lambda_dist * L_d
        kp_err = decoded_keypoint_error(hm_pred, hm_tgt, conf, valid, cfg)

        tot += float(L.item())
        tot_hm += float(L_hm.item())
        tot_d += float(L_d.item())
        tot_kp += float(kp_err.item())
        n += 1

    return {
        "loss": tot / max(n, 1),
        "loss_hm": tot_hm / max(n, 1),
        "loss_dist": tot_d / max(n, 1),
        "kp_error": tot_kp / max(n, 1),
        "example": example,
    }


