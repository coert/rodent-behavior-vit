@dataclass
class FrameItem:
    image_path: str
    xy: np.ndarray  # (K,2) original pixels
    conf: np.ndarray  # (K,) in [0,1]


@dataclass
class FrameLoadSummary:
    source_path: str
    total_rows: int
    kept_rows: int
    skipped_negative: int = 0
    skipped_missing_required: int = 0


def _coordinate_column(body_part: str, axis: str) -> str:
    return f"{body_part}_{axis}"


def _resolve_image_path(image_path: str, image_root: Path | None = None) -> str:
    path = Path(image_path)
    if path.is_absolute():
        return str(path)
    root = image_root if image_root is not None else Path.cwd()
    return str((root / path).resolve())


def _row_has_coordinates(row: pd.Series, body_part: str) -> bool:
    x_value = row.get(_coordinate_column(body_part, "x"))
    y_value = row.get(_coordinate_column(body_part, "y"))
    return pd.notna(x_value) and pd.notna(y_value)


def _required_body_parts_present(
    row: pd.Series, required_body_parts: list[str]
) -> bool:
    return all(
        _row_has_coordinates(row, body_part) for body_part in required_body_parts
    )


def _frame_item_from_annotation_row(
    row: pd.Series,
    *,
    image_root: Path | None = None,
) -> FrameItem:
    xy = np.zeros((K, 2), dtype=np.float32)
    conf = np.zeros(K, dtype=np.float32)

    for index, body_part in enumerate(BP):
        x_value = row.get(_coordinate_column(body_part, "x"))
        y_value = row.get(_coordinate_column(body_part, "y"))
        if pd.isna(x_value) or pd.isna(y_value):
            continue
        xy[index, 0] = float(x_value)
        xy[index, 1] = float(y_value)
        conf[index] = 1.0

    return FrameItem(
        image_path=_resolve_image_path(str(row["image_path"]), image_root=image_root),
        xy=xy,
        conf=conf,
    )


def _load_frame_items_from_annotation_csv(
    csv_path: str | Path,
    *,
    image_root: Path | None = None,
    required_body_parts: list[str] | None = None,
    return_summary: bool = False,
) -> List[FrameItem] | tuple[List[FrameItem], FrameLoadSummary]:
    csv_path = Path(csv_path)
    annotations = pd.read_csv(csv_path)
    resolved_image_root = image_root if image_root is not None else csv_path.parent
    required = required_body_parts or REQUIRED_SAMPLE_NAMES

    items: List[FrameItem] = []
    skipped_negative = 0
    skipped_missing_required = 0
    for _, row in annotations.iterrows():
        if int(row.get("label", 0)) != 1:
            skipped_negative += 1
            continue
        if not _required_body_parts_present(row, required):
            skipped_missing_required += 1
            continue
        items.append(
            _frame_item_from_annotation_row(row, image_root=resolved_image_root)
        )

    if not return_summary:
        return items

    return items, FrameLoadSummary(
        source_path=str(csv_path),
        total_rows=len(annotations),
        kept_rows=len(items),
        skipped_negative=skipped_negative,
        skipped_missing_required=skipped_missing_required,
    )


def _load_template_from_annotation_csv(
    template_csv: str | Path,
    *,
    image_root: Path | None = None,
    required_body_parts: list[str] | None = None,
) -> FrameItem:
    template_csv = Path(template_csv)
    annotations = pd.read_csv(template_csv)
    resolved_image_root = image_root if image_root is not None else template_csv.parent
    if len(annotations) != 1:
        raise ValueError("template CSV must contain exactly 1 row")

    row = annotations.iloc[0]
    required = required_body_parts or FRONT_SUBSET_NAMES
    if not _required_body_parts_present(row, required):
        missing = [
            body_part
            for body_part in required
            if not _row_has_coordinates(row, body_part)
        ]
        raise ValueError(
            "template CSV row is missing required keypoints: " + ", ".join(missing)
        )

    return _frame_item_from_annotation_row(row, image_root=resolved_image_root)


class RodentPoseDataset(Dataset):
    """
    - Loads image, resizes to 384x384
    - Scales DLC keypoints from original pixels to resized pixels
    - Builds heatmap targets and Pattern-3 y distance target
    """

    def __init__(
        self,
        items: List[FrameItem],
        template_Tn: torch.Tensor,
        subset_mask: torch.Tensor,
        kp_weight: torch.Tensor,
        cfg: Config,
    ):
        self.items = items
        self.template_Tn = template_Tn.detach().cpu()
        self.subset_mask = subset_mask.detach().cpu()
        self.kp_weight = kp_weight.detach().cpu()
        self.cfg = cfg

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, idx: int) -> dict:
        cfg = self.cfg
        it = self.items[idx]

        img = Image.open(it.image_path).convert("RGB")
        ow, oh = img.size  # W,H in original pixels

        img_rs = img.resize(
            (cfg.image_size, cfg.image_size), resample=Image.Resampling.BILINEAR
        )

        # scale keypoints to resized space
        xy = torch.tensor(it.xy, dtype=torch.float32)  # (K,2) original
        conf = torch.tensor(it.conf, dtype=torch.float32)  # (K,)
        sx = cfg.image_size / float(ow)
        sy = cfg.image_size / float(oh)
        xy_rs = xy.clone()
        xy_rs[:, 0] *= sx
        xy_rs[:, 1] *= sy

        valid = conf >= cfg.conf_min

        heatmaps = make_heatmaps(
            keypoints_xy=xy_rs,
            valid=valid,
            out_h=cfg.heatmap_size,
            out_w=cfg.heatmap_size,
            in_h=cfg.image_size,
            in_w=cfg.image_size,
            sigma_px_out=cfg.sigma_px_out,
        )

        # Pattern-3 target from DLC keypoints (resized space)
        y = grab_distance_target(
            X_xy_resized=xy_rs,
            conf=conf,
            Tn=self.template_Tn,
            subset_mask=self.subset_mask,
            kp_weight=self.kp_weight,
            cfg=cfg,
        )

        x = (
            torch.from_numpy(np.array(img_rs)).permute(2, 0, 1).float() / 255.0
        )  # (3,384,384)

        return {
            "image": x,
            "heatmaps": heatmaps,  # (K,96,96)
            "conf": conf,  # (K,)
            "valid": valid.float(),  # (K,)
            "y": y.float(),  # scalar
        }


