def default_lr_for_backbone(backbone: str) -> float:
    return 3e-4 if backbone == "resnet18" else 1e-5


def uses_timm_backbone(backbone: str) -> bool:
    return backbone != "resnet18"


def apply_large_batch_training_defaults(
    cfg: Config,
    *,
    user_provided_lr: bool,
    user_provided_scheduler: bool,
    user_provided_warmup_epochs: bool,
    user_provided_warmup_start_factor: bool,
    user_provided_min_lr_ratio: bool,
) -> None:
    if not uses_timm_backbone(cfg.backbone):
        return
    if cfg.batch_size < 48:
        return
    if not user_provided_lr:
        cfg.lr = 2e-5
    if not user_provided_scheduler:
        cfg.scheduler = "cosine"
    if not user_provided_warmup_epochs:
        cfg.warmup_epochs = 2
    if not user_provided_warmup_start_factor:
        cfg.warmup_start_factor = 0.5
    if not user_provided_min_lr_ratio:
        cfg.min_lr_ratio = 0.1


def learning_rate_for_epoch(cfg: Config, epoch: int) -> float:
    if cfg.scheduler is None:
        return cfg.lr

    if cfg.scheduler != "cosine":
        raise ValueError(f"Unsupported scheduler: {cfg.scheduler}")

    if cfg.warmup_epochs > 0 and epoch <= cfg.warmup_epochs:
        if cfg.warmup_epochs == 1:
            return cfg.lr
        progress = (epoch - 1) / max(cfg.warmup_epochs - 1, 1)
        factor = cfg.warmup_start_factor + (1.0 - cfg.warmup_start_factor) * progress
        return cfg.lr * factor

    decay_epochs = max(cfg.epochs - cfg.warmup_epochs, 1)
    decay_span = max(decay_epochs - 1, 1)
    completed_decay_epochs = min(max(epoch - cfg.warmup_epochs - 1, 0), decay_span)
    cosine_progress = completed_decay_epochs / decay_span
    min_lr = cfg.lr * cfg.min_lr_ratio
    cosine_factor = 0.5 * (1.0 + math.cos(math.pi * cosine_progress))
    return min_lr + (cfg.lr - min_lr) * cosine_factor


def set_optimizer_lr(opt: torch.optim.Optimizer, lr: float) -> None:
    for group in opt.param_groups:
        group["lr"] = lr


