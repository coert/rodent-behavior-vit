def build_subset_and_weights(cfg: Config) -> tuple[torch.Tensor, torch.Tensor]:
    subset_mask = torch.zeros(K, dtype=torch.bool)
    for name in FRONT_SUBSET_NAMES:
        subset_mask[IDX[name]] = True

    kp_weight = torch.ones(K)
    kp_weight[IDX["front_left_paw"]] = cfg.paw_w
    kp_weight[IDX["front_right_paw"]] = cfg.paw_w
    kp_weight[IDX["front_left_knee"]] = cfg.knee_w
    kp_weight[IDX["front_right_knee"]] = cfg.knee_w
    kp_weight[IDX["front_left_thai"]] = cfg.thai_w
    kp_weight[IDX["front_right_thai"]] = cfg.thai_w
    return subset_mask, kp_weight


