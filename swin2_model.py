def decoded_keypoint_error(
    heatmaps_pred: torch.Tensor,
    heatmaps_target: torch.Tensor,
    conf: torch.Tensor,
    valid: torch.Tensor,
    cfg: Config,
) -> torch.Tensor:
    pred_coords = soft_argmax_2d(heatmaps_pred, beta=cfg.softargmax_beta) * float(
        cfg.stride
    )
    target_coords = soft_argmax_2d(heatmaps_target, beta=cfg.softargmax_beta) * float(
        cfg.stride
    )
    per_keypoint = torch.norm(pred_coords - target_coords, dim=-1)
    weights = conf * valid
    return (weights * per_keypoint).sum() / (weights.sum() + cfg.eps)


def render_keypoints_for_tensorboard(
    image: torch.Tensor,
    coords_hm: torch.Tensor,
    *,
    image_size: int,
    heatmap_size: int,
    color: tuple[float, float, float],
    radius: int = 2,
) -> torch.Tensor:
    canvas = image.detach().float().cpu().clone()
    scale = image_size / float(heatmap_size)
    rgb = torch.tensor(color, dtype=canvas.dtype).view(3, 1, 1)

    for coord in coords_hm:
        if not torch.isfinite(coord).all():
            continue
        x = int(round(float(coord[0].item()) * scale))
        y = int(round(float(coord[1].item()) * scale))
        x = max(0, min(image_size - 1, x))
        y = max(0, min(image_size - 1, y))
        x0 = max(0, x - radius)
        x1 = min(image_size, x + radius + 1)
        y0 = max(0, y - radius)
        y1 = min(image_size, y + radius + 1)
        canvas[:, y0:y1, x0:x1] = rgb

    return canvas.clamp(0.0, 1.0)


def _normalize_heatmap_for_tensorboard(heatmap: torch.Tensor) -> torch.Tensor:
    heatmap = heatmap.detach().float().cpu()
    heatmap = heatmap - heatmap.amin()
    heatmap = heatmap / heatmap.amax().clamp_min(1e-6)
    return torch.stack(
        [heatmap[0], heatmap[0] * 0.4, torch.zeros_like(heatmap[0])], dim=0
    )


def capture_tensorboard_example(
    images: torch.Tensor,
    heatmaps_target: torch.Tensor,
    heatmaps_pred: torch.Tensor,
    image_size: int,
    softargmax_beta: float = 50.0,
) -> dict[str, torch.Tensor]:
    image = images[0].detach().float().cpu().clamp(0.0, 1.0)
    heatmap_size = int(heatmaps_target.shape[-1])
    target_heatmap = heatmaps_target[0].detach().float().cpu().amax(dim=0, keepdim=True)
    pred_heatmap = heatmaps_pred[0].detach().float().cpu().amax(dim=0, keepdim=True)
    target_coords = soft_argmax_2d(heatmaps_target[:1].detach(), beta=softargmax_beta)[
        0
    ].cpu()
    pred_coords = soft_argmax_2d(heatmaps_pred[:1].detach(), beta=softargmax_beta)[
        0
    ].cpu()

    target_heatmap = F.interpolate(
        target_heatmap.unsqueeze(0),
        size=(image_size, image_size),
        mode="bilinear",
        align_corners=False,
    ).squeeze(0)
    pred_heatmap = F.interpolate(
        pred_heatmap.unsqueeze(0),
        size=(image_size, image_size),
        mode="bilinear",
        align_corners=False,
    ).squeeze(0)

    target_rgb = _normalize_heatmap_for_tensorboard(target_heatmap)
    pred_rgb = _normalize_heatmap_for_tensorboard(pred_heatmap)
    target_keypoints = render_keypoints_for_tensorboard(
        image,
        target_coords,
        image_size=image_size,
        heatmap_size=heatmap_size,
        color=(0.0, 1.0, 0.0),
    )
    pred_keypoints = render_keypoints_for_tensorboard(
        image,
        pred_coords,
        image_size=image_size,
        heatmap_size=heatmap_size,
        color=(1.0, 0.2, 0.2),
    )
    combined_keypoints = render_keypoints_for_tensorboard(
        target_keypoints,
        pred_coords,
        image_size=image_size,
        heatmap_size=heatmap_size,
        color=(1.0, 0.2, 0.2),
    )
    return {
        "image": image,
        "target_heatmap": target_rgb,
        "pred_heatmap": pred_rgb,
        "target_overlay": torch.clamp(0.7 * image + 0.5 * target_rgb, 0.0, 1.0),
        "pred_overlay": torch.clamp(0.7 * image + 0.5 * pred_rgb, 0.0, 1.0),
        "target_keypoints": target_keypoints,
        "pred_keypoints": pred_keypoints,
        "combined_keypoints": combined_keypoints,
    }


